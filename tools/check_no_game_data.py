#!/usr/bin/env python3
"""Fail if anything game-derived is tracked in this (public) repository.

    python tools/check_no_game_data.py                    # what is (or is staged to be) committed
    python tools/check_no_game_data.py --history A..B     # every file added or changed in commits A..B
    python tools/check_no_game_data.py --history HEAD     # ... in the whole history
    python tools/check_no_game_data.py --keys keys/ps3.keys   # also look for the real key bytes (local only)

Run it before you commit; CI runs it on every push and pull request.

What counts as game-derived (see docs/CI.md):
  path     packages, licenses, SELF/ELF/PRX, EDAT/SDAT, PARAM.SFO, T55DATA*,
           *.keys and anything under keys/, game/, build/, deps/, the lifters'
           output (ppu_recomp*.cpp/.h, spu_recomp.c/.h, spu_workloads.c)
  size     anything over 1 MiB
  magic    ELF, SCE (SELF/SPRX), PKG, NPD (EDAT/SDAT), PSF (PARAM.SFO), PAMF,
           RIFF (AT3/WAV), TRP (trophies)
  binary   anything that is not UTF-8 text (none of our sources are binary; see ALLOW)
  profile  tools/gamedll/t5dr_lifted.proftext, the lifted code's PGO profile, is checked by
           tools/profile_check.py instead of the size and content checks: function names,
           hashes and execution counts only, nothing else
  content  the lifters' "generated" headers, dense lifted-function names, a
           GIT binary patch, long hex or base64 runs (embedded binaries), and a
           decryption key name next to a long hex value or byte list
  --keys   the actual bytes of each key in a local keys file, as raw bytes,
           hex text or a C byte list -- the values are never printed

The checks read the blobs git would commit (the index, or the commits in
--history), not the working tree.
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = ROOT         # --repo
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import profile_check  # noqa: E402 -- the one exempt path: the lifted code's PGO profile (names and counts)
LIMIT = 1 << 20     # 1 MiB

# Paths exempt from the binary / magic checks -- only for fixtures we made
# ourselves. Keep it empty unless there is a reason, and say the reason here.
ALLOW = {
    # Our own launcher icon (a "T5" drawn with Pillow in Arial Bold, 2026-10-18), compiled
    # into T5DR Online.exe so virus scanners see an ordinary application.
    "launcher/stub/t5dr.ico",
    # The same pictures with the small sizes as bitmaps instead of PNG (tools/make_stub_icon.py), for the
    # stub variants: a PNG is compressed data and makes the resource section look packed.
    "launcher/stub/t5dr_bmp.ico",
}

# Exact old file versions (git blob ids) exempt from the binary check, for --history: our own sources
# that once held a stray control byte, fixed since. Only ever add a blob after looking at it.
ALLOW_BLOBS = {
    # lobby/tests/test_nat2.py with one raw 0x02 byte in a fake packet's string literal (fixed in 5d51c99)
    "dc6ade695600729797864e05d410bae26ceec2ba",
    "98a405b7a4242823d0beb4694e02c8d1ad7fab1e",
    "00946d9994541447c1b0e9d28d6d0107f5c190e6",
}


def blob_id(b):
    return hashlib.sha1(b"blob %d\0" % len(b) + b).hexdigest()


BLOCKED_EXT = {
    ".pkg", ".rap", ".rif", ".edat", ".sdat", ".self", ".sprx", ".prx", ".elf",
    ".sfo", ".pfd", ".trp", ".at3", ".pam", ".pamf", ".keys", ".bin",
}
BLOCKED_NAMES = {"eboot.bin", "param.sfo", "param.pfd", "ps3logo.dat", "icon0.png", "icon1.pam",
                 "pic0.png", "pic1.png", "pic2.png", "snd0.at3",
                 "spu_workloads.c", "spu_recomp.c", "spu_recomp.h"}
BLOCKED_NAME_RE = re.compile(r"^(?:ppu_recomp.*\.(?:cpp|h|c)|t55data.*)$", re.I)
# Git-ignored trees that hold game files, keys, or reference clones.
BLOCKED_DIRS = {"keys", "game", "build", "deps", "_ref", "usrdir", "dev_hdd0", "ps3_game", "gamedata", "scratch"}

MAGIC = [
    (b"\x7fELF", "ELF image"),
    (b"SCE\x00", "SCE container (SELF/SPRX)"),
    (b"\x7fPKG", "PS3 package"),
    (b"NPD\x00", "NPDRM data (EDAT/SDAT)"),
    (b"\x00PSF", "PARAM.SFO"),
    (b"PAMF", "PAMF movie"),
    (b"RIFF", "RIFF payload (AT3/WAV)"),
    (b"\xdc\xa2\x4d\x00", "trophy file"),
]

# Built by concatenation so this file does not trip its own check.
GENERATED = [
    ("/* Auto-generated by " + "ppu_lifter.py", "ppu_lifter.py output (lifted game code)"),
    ("/* Auto-generated by " + "spu_lifter.py", "spu_lifter.py output (lifted game code)"),
    ("/* spu_workloads.c -- " + "GENERATED", "build_spu_workloads.py output"),
]
LIFTED_NAME = re.compile(r"(?:func|sub)_[0-9A-Fa-f]{8}\b")
LIFTED_MAX = 50
# The header git writes before a base85 payload: on a line of its own, then
# "literal N" or "delta N" -- not the phrase mentioned in prose.
BIN_PATCH = re.compile(r"(?m)^GIT binary patch\r?\n(?:literal|delta) \d+")
HEX_RUN = re.compile(r"[0-9A-Fa-f]{512,}")
B64_RUN = re.compile(r"[A-Za-z0-9+/]{2048,}")
KEY_NAME = re.compile(
    r"\b(?:NP_KLIC_KEY|NP_KLIC_FREE|NP_RIF_KEY|NP_IDPS_CONST|NP_OMAC_KEY_\d|NP_PSP_KEY_\d|"
    r"RAP_KEY|RAP_PBOX|RAP_E1|RAP_E2|EDAT_KEY_\d|EDAT_HASH_\d|EDAT_IV|SDAT_KEY|"
    r"PKG_AES_KEY\w*|\w*_ERK|\w*_RIV|\w*KLICENSEE\w*)\b")
LONG_HEX = re.compile(r"[0-9A-Fa-f]{32,}")
BYTE_LIT = re.compile(r"0x[0-9A-Fa-f]{2}\b")


def git(*args, inp=None):
    r = subprocess.run(["git", "-C", REPO, *args], input=inp, capture_output=True)
    if r.returncode != 0:
        sys.exit(f"[check_no_game_data] git {' '.join(args)} failed: {r.stderr.decode(errors='replace').strip()}")
    return r.stdout


def index_entries():
    """(path, blob) for every file in the index -- what the next commit holds."""
    out = []
    for rec in git("ls-files", "-s", "-z").split(b"\0"):
        if not rec:
            continue
        meta, path = rec.split(b"\t", 1)
        mode, sha, _stage = meta.split()
        if mode != b"160000":                   # submodule: a commit, not a file
            out.append((path.decode("utf-8", "replace"), sha.decode()))
    return out


def history_entries(rev_range):
    """(path, blob) for every file added or modified by the commits in rev_range."""
    seen, out = set(), []
    for commit in git("rev-list", *rev_range.split()).decode().split():
        raw = git("diff-tree", "-r", "-z", "--root", "--no-commit-id", "--no-renames",
                  "--diff-filter=AMT", commit).split(b"\0")
        for i in range(0, len(raw) - 1, 2):
            meta, path = raw[i], raw[i + 1]
            if not meta.startswith(b":"):
                continue
            _om, nmode, _osha, nsha, _st = meta[1:].split()
            key = (path, nsha)
            if nmode != b"160000" and key not in seen:
                seen.add(key)
                out.append((f"{path.decode('utf-8', 'replace')} @{commit[:10]}", nsha.decode()))
    return out


def read_blobs(shas):
    """{sha: bytes} through one `git cat-file --batch`."""
    uniq = sorted(set(shas))
    if not uniq:
        return {}
    data = git("cat-file", "--batch", inp=("\n".join(uniq) + "\n").encode())
    blobs, pos = {}, 0
    for sha in uniq:
        nl = data.index(b"\n", pos)
        head = data[pos:nl].split()
        if len(head) < 3 or head[1] != b"blob":
            sys.exit(f"[check_no_game_data] cannot read blob {sha}")
        size = int(head[2])
        blobs[sha] = data[nl + 1:nl + 1 + size]
        pos = nl + 1 + size + 1
    return blobs


CONTROL = re.compile(rb"[\x00-\x08\x0e-\x1a\x1c-\x1f]")


def is_text(b):
    """UTF-8 without NULs or stray control bytes: every source we write. A
    16-byte license or any other binary fails this almost surely."""
    if CONTROL.search(b):
        return False
    try:
        b.decode("utf-8")
    except UnicodeDecodeError:
        return False
    return True


def check_path(path):
    parts = [p.lower() for p in path.split(" @")[0].split("/")]
    name = parts[-1]
    found = []
    if name in BLOCKED_NAMES or BLOCKED_NAME_RE.match(name):
        found.append(f"file name '{parts[-1]}' is game data or lifted output")
    ext = os.path.splitext(name)[1]
    if ext in BLOCKED_EXT and name not in BLOCKED_NAMES:
        found.append(f"'{ext}' files are game data, licenses or keys")
    if ext == ".t5replay":
        found.append("'.t5replay' files are players' replays (their matches, maybe their names): never in the repository")
    bad_dirs = [d for d in parts[:-1] if d in BLOCKED_DIRS]
    if bad_dirs:
        found.append(f"lives under {bad_dirs[0]}/, which holds game files, keys or local clones")
    return found


def check_content(path, b):
    found = []
    clean = path.split(" @")[0]
    if clean == profile_check.PROFILE_PATH:
        # The lifted code's PGO profile (docs/RENDER_PERF.md "Profile-guided optimisation"): 7,000+ lifted
        # function names and over 1 MiB, so the generic checks below would refuse it. It is accepted at this
        # one path only when it is nothing but function names, structural hashes and execution counts.
        return ["PGO profile: " + p for p in profile_check.check(b)]
    if len(b) > LIMIT:
        found.append(f"{len(b):,} bytes is over the 1 MiB limit")
    if clean not in ALLOW:
        for magic, what in MAGIC:
            if b.startswith(magic):
                found.append(f"starts like a {what}")
        if not is_text(b) and blob_id(b) not in ALLOW_BLOBS:
            found.append("binary file (NUL/control bytes or not UTF-8); our sources are text")
    t = b.decode("latin-1")
    head = t[:512]
    for marker, what in GENERATED:
        if marker in head:
            found.append(what)
    n = len(LIFTED_NAME.findall(t))
    if n >= LIFTED_MAX:
        found.append(f"{n} lifted function names (func_/sub_XXXXXXXX): looks like lifted code")
    if BIN_PATCH.search(t):
        found.append("contains a GIT binary patch (a binary payload)")
    if HEX_RUN.search(t):
        found.append("contains a hex run of 512+ digits (an embedded binary?)")
    if B64_RUN.search(t):
        found.append("contains a base64 run of 2048+ characters (an embedded binary?)")
    for m in KEY_NAME.finditer(t):
        window = t[m.start():m.start() + 600]
        blank = re.search(r"\n[ \t]*\n", window)
        if blank:
            window = window[:blank.start()]
        if LONG_HEX.search(window) or len(BYTE_LIT.findall(window)) >= 16:
            line = t.count("\n", 0, m.start()) + 1
            found.append(f"line {line}: key name {m.group(0)} next to a long hex value or byte list")
    return found


def load_key_patterns(path):
    """[(name, value bytes)] for each key in a NAME=HEX file."""
    pats = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            name, val = line.split("=", 1)
            try:
                v = bytes.fromhex(val.strip())
            except ValueError:
                continue
            if len(v) >= 8:
                pats.append((name.strip(), v))
    return pats


def check_keys(b, keys):
    found = []
    low = b.lower()
    # Every 0xNN byte literal in the file, joined, so a C/Python byte list
    # matches however it is wrapped or spaced.
    lits = bytes(int(x, 16) for x in re.findall(rb"0[xX]([0-9A-Fa-f]{2})\b", b))
    for name, v in keys:
        if v in b or v.hex().encode() in low or v in lits:
            found.append(f"contains the value of local key {name}")
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--history", metavar="RANGE",
                    help="check the files added or changed by these commits (git rev-list syntax) instead of the index")
    ap.add_argument("--keys", metavar="FILE", help="a local NAME=HEX keys file; fail if any key value is tracked")
    ap.add_argument("--repo", default=ROOT, help="repository to check (default: this one)")
    a = ap.parse_args()
    global REPO
    REPO = a.repo
    if a.keys and not os.path.isfile(a.keys):
        sys.exit(f"[check_no_game_data] no keys file at {a.keys}")

    entries = history_entries(a.history) if a.history else index_entries()
    blobs = read_blobs(sha for _, sha in entries)
    keys = load_key_patterns(a.keys) if a.keys else []

    bad = 0
    for path, sha in entries:
        problems = check_path(path) + check_content(path, blobs[sha])
        if keys:
            problems += check_keys(blobs[sha], keys)
        for p in problems:
            bad += 1
            print(f"{path}: {p}")
            if os.environ.get("GITHUB_ACTIONS") == "true":
                print(f"::error file={path.split(' @')[0]}::game-data guard: {p}")

    what = f"commits {a.history}" if a.history else "the index"
    extra = f", {len(keys)} local key(s)" if keys else ""
    if bad:
        print(f"\n{bad} problem(s) in {len(entries)} file(s) of {what}{extra}. "
              "This repository is public: nothing game-derived may be committed (see docs/CI.md).")
        sys.exit(1)
    print(f"ok: {len(entries)} file(s) of {what} checked{extra}, nothing game-derived")


if __name__ == "__main__":
    main()
