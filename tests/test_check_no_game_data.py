"""tools/check_no_game_data.py on throwaway repositories: each kind of
game-derived file is caught, ordinary sources pass, history is searched, and
--keys finds a key's bytes without printing them. Every "game file" here is a
few synthetic bytes made on the spot."""
import os
import subprocess
import tempfile
import unittest

from helpers import PY, TOOLS, fake_bytes, put, write_keys

GUARD = os.path.join(TOOLS, "check_no_game_data.py")


def git(repo, *args):
    subprocess.run(["git", "-C", repo, "-c", "user.name=t", "-c", "user.email=t@example.invalid",
                    "-c", "core.autocrlf=false", *args], check=True, capture_output=True)


class Guard(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.repo = os.path.join(self.tmp.name, "repo")
        os.makedirs(self.repo)
        git(self.repo, "init", "-q")
        self.add("tools/ok.py", "print('hello')\n")
        self.add("README.md", "# fine\nRAP_KEY and NPDRM_0001_ERK are named here without values.\n")

    def add(self, rel, data):
        p = os.path.join(self.repo, *rel.split("/"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        put(p, data)
        git(self.repo, "add", "-f", rel)

    def guard(self, *args, env=None):
        e = {k: v for k, v in os.environ.items() if k != "GITHUB_ACTIONS"}
        e.update(env or {})
        r = subprocess.run([PY, GUARD, "--repo", self.repo, *args], capture_output=True, text=True, env=e)
        return r.returncode, r.stdout + r.stderr

    def assertCaught(self, rel, data, why):
        self.add(rel, data)
        code, out = self.guard()
        self.assertEqual(code, 1, out)
        self.assertIn(rel, out)
        self.assertIn(why, out)

    def test_clean_repo_passes(self):
        code, out = self.guard()
        self.assertEqual(code, 0, out)
        self.assertIn("ok: 2 file(s)", out)

    def test_elf(self):
        self.assertCaught("src/thing.dat", b"\x7fELF\x02\x02\x01" + fake_bytes("elf", 200), "ELF image")

    def test_self(self):
        self.assertCaught("src/thing.dat", b"SCE\0" + fake_bytes("self", 200), "SCE container")

    def test_pkg(self):
        self.assertCaught("src/thing.dat", b"\x7fPKG" + fake_bytes("pkg", 200), "PS3 package")

    def test_pamf_riff(self):
        self.assertCaught("media/a.dat", b"PAMF0041" + fake_bytes("pamf", 64), "PAMF movie")
        self.assertCaught("media/b.dat", b"RIFF\x10\0\0\0WAVEfmt ", "RIFF payload")

    def test_rap_by_name(self):
        self.assertCaught("licenses/UP0000-TEST00000_00-0000000000000000.rap", fake_bytes("rap"), "'.rap' files")

    def test_replay_by_name(self):
        self.assertCaught("native/replays/T5R-20261019-120000-abcd.t5replay", b"T5REPLAY 1\n{}\n", "players' replays")
        self.assertCaught("docs/example.t5replay", b"T5REPLAY 1\n{}\n", "players' replays")

    def test_binary(self):
        self.assertCaught("assets/blob.dat", fake_bytes("blob", 64), "binary file")

    def test_big_file(self):
        self.assertCaught("docs/big.txt", "x" * ((1 << 20) + 1), "over the 1 MiB limit")

    def test_keys_dir_and_file(self):
        self.assertCaught("keys/notes.txt", "nothing secret\n", "lives under keys/")
        self.assertCaught("conf/ps3.keys", "# empty\n", "'.keys' files")

    def test_lifted_names(self):
        self.assertCaught("src/ppu_recomp_000.cpp", "// empty\n", "lifted output")
        self.assertCaught("x/spu_recomp.c", "// empty\n", "lifted output")

    def test_lifted_content(self):
        self.assertCaught("src/gen.cpp", "/* Auto-generated by " + "ppu_lifter.py -- do not edit by hand. */\n",
                          "ppu_lifter.py output")
        body = "".join(f"void func_{0x10000 + 4 * i:08X}(ppu_context& ctx) {{}}\n" for i in range(60))
        self.assertCaught("src/pasted.cpp", body, "lifted function names")

    def test_key_name_with_hex(self):
        val = fake_bytes("not a real key").hex().upper()
        self.assertCaught("tools/conf.txt", f"RAP_KEY={val}\n", "key name RAP_KEY")
        lst = ", ".join(f"0x{b:02X}" for b in fake_bytes("not a real key either"))
        self.assertCaught("tools/vault.h", f"constexpr u8 NP_KLIC_KEY[0x10] = {{\n\t{lst}\n}};\n",
                          "key name NP_KLIC_KEY")

    def test_embedded_blobs(self):
        self.assertCaught("tools/a.py", "DATA = '" + fake_bytes("hex", 300).hex() + "'\n", "hex run")
        self.assertCaught("p/x.patch", "diff --git a/x b/x\nGIT binary patch\nliteral 3\n", "GIT binary patch")

    def test_history(self):
        git(self.repo, "commit", "-q", "-m", "base")
        self.add("game/EBOOT.elf", b"\x7fELF" + fake_bytes("elf", 64))
        git(self.repo, "commit", "-q", "-m", "oops")
        git(self.repo, "rm", "-q", "--cached", "game/EBOOT.elf")
        git(self.repo, "commit", "-q", "-m", "remove it again")
        code, out = self.guard()                       # gone from the tree ...
        self.assertEqual(code, 0, out)
        code, out = self.guard("--history", "HEAD~2..HEAD")   # ... but not from the history
        self.assertEqual(code, 1, out)
        self.assertIn("game/EBOOT.elf @", out)
        code, out = self.guard("--history", "HEAD~2")   # base only
        self.assertEqual(code, 0, out)

    def test_local_keys_never_printed(self):
        keys = {"RAP_KEY": fake_bytes("local key a"), "NPDRM_0001_RIV": fake_bytes("local key b")}
        kp = os.path.join(self.tmp.name, "ps3.keys")
        write_keys(kp, keys)
        code, out = self.guard("--keys", kp)
        self.assertEqual(code, 0, out)
        # The value hidden in prose, lower case, no key name nearby.
        self.add("docs/notes.md", "see " + keys["NPDRM_0001_RIV"].hex() + " for details\n")
        code, out = self.guard("--keys", kp)
        self.assertEqual(code, 1, out)
        self.assertIn("contains the value of local key NPDRM_0001_RIV", out)
        for v in keys.values():
            self.assertNotIn(v.hex(), out.lower())

    def test_github_annotation(self):
        self.add("x/a.rap", fake_bytes("rap"))
        code, out = self.guard(env={"GITHUB_ACTIONS": "true"})
        self.assertEqual(code, 1)
        self.assertIn("::error file=x/a.rap::", out)

    def test_this_repository_is_clean(self):
        r = subprocess.run([PY, GUARD], capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)


if __name__ == "__main__":
    unittest.main()
